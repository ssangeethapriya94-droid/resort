// Turns the originals in ../photos-originals into optimised WebP files in public/img
// (640 / 1280 / 1920 px wide) and regenerates src/data/imageMeta.js.
//
//   npm run images
//
// The file name (without extension) becomes the image name used in src/data/site.js.
// e.g. photos-originals/sunrise-sea.jpg  ->  name "sunrise-sea"
// Warm up grey photos:  WARM=beach-pano,waves npm run images
import sharp from 'sharp';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.resolve(root, '../photos-originals');
const OUT = path.join(root, 'public/img');
const WARM = new Set((process.env.WARM || '').split(',').filter(Boolean));

fs.mkdirSync(OUT, { recursive: true });
const meta = {};
for (const file of fs.readdirSync(SRC)) {
  if (!/\.(jpe?g|png|webp)$/i.test(file)) continue;
  const name = path.parse(file).name.toLowerCase().replace(/[^a-z0-9-]+/g, '-');
  const src = path.join(SRC, file);
  const m = await sharp(src).metadata();
  const widths = [640, 1280, 1920].filter((w) => w <= m.width);
  if (!widths.length) widths.push(m.width);
  for (const w of widths) {
    let p = sharp(src).rotate().resize({ width: w }).modulate({ saturation: 1.12, brightness: 1.03 });
    if (WARM.has(name)) p = p.recomb([[1.06, 0, 0], [0, 1, 0], [0, 0, 0.93]]);
    await p.webp({ quality: 78 }).toFile(path.join(OUT, `${name}-${w}.webp`));
  }
  meta[name] = { w: m.width, h: m.height, widths };
  console.log('✓', name, widths.join('/'));
}
fs.writeFileSync(path.join(root, 'src/data/imageMeta.js'), '// Generated by scripts/make-images.mjs\nexport const IMAGES = ' + JSON.stringify(meta, null, 2) + ';\n');
console.log('imageMeta.js updated');
